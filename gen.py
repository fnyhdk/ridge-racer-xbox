#!/usr/bin/env python3
"""Generates the translated game for the Xbox build.

The translation itself is the native runtime's: this script imports
`tools/m0/build.py` from the decompilation and calls the same functions, so
the Xbox build cannot drift from what boots on the desktop. Only the
description of the disc changes -- on the Xbox the files sit next to the XBE,
on the drive the kernel mounts as D:.

    python3 gen.py PSX.EXE --iso SLPS-00001.iso --out gen

Like `build.py`, nothing written here belongs under version control: it is the
game's own code and data in another notation.
"""
import argparse
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
DECOMP = os.environ.get("DECOMP", os.path.join(os.path.dirname(HERE), "rr-decomp-0.1.0"))
sys.path.insert(0, os.path.join(DECOMP, "tools", "m0"))

import build  # noqa: E402  (tools/m0/build.py)

# Where the files land on the Xbox. The Makefile copies them there.
XBOX_DISC = r"D:\disc.iso"
XBOX_TRACKS = r"D:\tracks"


def msf(s):
    mm, ss, ff = (int(x) for x in s.split(":"))
    return (mm * 60 + ss) * 75 + ff


def split_cue(cue, out):
    """A sheet with one file per track, for a dump made as a single image.

    build.read_cue counts each FILE as one track, as Redump-style dumps have
    it. ImgBurn, CDRWIN and others more often write the whole disc as one
    .bin or .img, the INDEX lines then counting from the start of that file.
    Such an image is cut at each track's INDEX 00 (its pregap), which gives
    the same files as a per-track dump; a PREGAP line, silence the image
    leaves out, is written back as zeros. Returns the sheet to read: `cue`
    itself when it already has a file per track."""
    dir = os.path.dirname(os.path.abspath(cue))
    files, tracks = [], []
    for line in open(cue, encoding="utf-8", errors="replace"):
        l = line.strip()
        if l.startswith("FILE "):
            files.append(os.path.join(dir, l.split('"')[1] if '"' in l else l.split()[1]))
        elif l.startswith("TRACK "):
            parts = l.split()
            tracks.append({"n": int(parts[1]), "type": parts[2], "file": len(files) - 1,
                           "index": {}, "pregap": 0})
        elif l.startswith("INDEX ") and tracks:
            parts = l.split()
            tracks[-1]["index"][int(parts[1])] = msf(parts[2])
        elif l.startswith("PREGAP ") and tracks:
            tracks[-1]["pregap"] = msf(l.split()[1])
    if len(files) != 1 or len(tracks) < 2:
        return cue
    image = files[0]
    if not os.path.exists(image):
        sys.exit("the sheet names a file that is not there: " + image)
    raw = [t for t in tracks if not t["type"].endswith("/2352") and t["type"] != "AUDIO"]
    if raw:
        sys.exit("%s: track %d is %s; a single-file image needs raw 2352-byte "
                 "sectors throughout -- rip it again in raw mode"
                 % (cue, raw[0]["n"], raw[0]["type"]))
    os.makedirs(out, exist_ok=True)
    end = os.path.getsize(image) // 2352
    sheet = []
    with open(image, "rb") as src:
        for i, t in enumerate(tracks):
            first = t["index"].get(0, t["index"][1])
            last = tracks[i + 1]["index"].get(0, tracks[i + 1]["index"][1]) if i + 1 < len(tracks) else end
            name = "track%02d.bin" % t["n"]
            src.seek(first * 2352)
            with open(os.path.join(out, name), "wb") as dst:
                dst.write(bytes(2352 * t["pregap"]))
                left = (last - first) * 2352
                while left:
                    chunk = src.read(min(left, 1 << 20))
                    if not chunk:
                        sys.exit("%s ends inside track %d" % (image, t["n"]))
                    dst.write(chunk)
                    left -= len(chunk)
            sheet.append('FILE "%s" BINARY' % name)
            sheet.append("  TRACK %02d %s" % (t["n"], t["type"]))
            for k in sorted(t["index"]):
                f = t["index"][k] - first + t["pregap"]
                sheet.append("    INDEX %02d %02d:%02d:%02d" % (k, f // 4500, f // 75 % 60, f % 75))
    split = os.path.join(out, "split.cue")
    open(split, "w").write("\n".join(sheet) + "\n")
    print("cue: one image, %d tracks -> split into %s" % (len(tracks), out))
    return split


def write_disc(iso, cue, dest):
    """The same table as build.write_disc, with the paths the Xbox will see.

    Track files are renamed track02.bin, track03.bin...: the names a dump
    carries ("Ridge Racer (Japan) (Track 02).bin") are longer than FATX and
    XISO are comfortable with, and the number is all the runtime needs."""
    sectors = (os.path.getsize(iso) + 2047) // 2048 if iso else 0
    if cue:
        cue = split_cue(cue, os.path.join(os.path.dirname(dest), "split"))
    tracks = build.read_cue(cue) if cue else []
    lines = ["/* generated by xbox/gen.py -- do not check in */",
             "struct cdfile { unsigned int lba, size; const char *path; };",
             "const struct cdfile CDFILES[] = { {0, 0, 0} };",
             "const int NCDFILES = 0;",
             'const char *CD_META = "%s";' % (XBOX_DISC.replace("\\", "\\\\") if iso else ""),
             "const unsigned int CD_META_SECTORS = %u;" % sectors,
             "",
             "struct cdtrack { unsigned int start, length, skip; const char *file; };",
             "const struct cdtrack CDTRACKS[] = {"]
    copies = []
    for t in tracks:
        n = os.path.getsize(t["file"]) // 2352
        name = "track%02d.bin" % t["n"]
        # The data track is read from disc.iso: its file would only fill the
        # Xbox with a second copy of the disc.
        if t["audio"]:
            copies.append((t["file"], name))
        lines.append('  {%u, %u, %u, "%s"},   /* track %02d%s */'
                     % (t["start"], n, t["skip"],
                        (XBOX_TRACKS + "\\" + name).replace("\\", "\\\\"),
                        t["n"], "" if t["audio"] else "  data"))
    if not tracks:
        lines.append("  {0, 0, 0, 0}")
    lines.append("};")
    lines.append("const int NCDTRACKS = %d;" % len(tracks))
    open(dest, "w").write("\n".join(lines) + "\n")
    return sectors, tracks, copies


def main():
    p = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("exe", help="your copy of PSX.EXE")
    p.add_argument("--iso", required=True, help="image of the disc's data track")
    p.add_argument("--cue", help="the disc's CUE sheet, for the music")
    p.add_argument("--out", default=os.path.join(HERE, "gen"))
    a = p.parse_args()

    os.makedirs(a.out, exist_ok=True)
    defined, stubs = build.write_game(a.exe, os.path.join(a.out, "game.c"))
    n = build.write_table(defined, os.path.join(a.out, "table.c"))
    sectors, tracks, copies = write_disc(a.iso, a.cue, os.path.join(a.out, "cdfiles.c"))

    print("%d functions translated, %d stubs" % (n, len(stubs)))
    for name, reason in stubs:
        print("   %-24s %s" % (name, reason))
    print("disc: %s, %d sectors -> %s" % (a.iso, sectors, XBOX_DISC))
    # The Makefile reads this list to copy the audio tracks next to the XBE.
    with open(os.path.join(a.out, "tracks.txt"), "w") as f:
        for src, name in copies:
            f.write("%s\t%s\n" % (src, name))
    if tracks:
        print("tracks: %d -> %s" % (len(tracks), XBOX_TRACKS))
    else:
        print("tracks: none (--cue missing) -- no music, effects only")


if __name__ == "__main__":
    main()
